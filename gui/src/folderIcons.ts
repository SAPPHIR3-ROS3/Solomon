const standaloneFolderIcons: Record<string, string> = {
  Desktop: "desktop",
};


export function folderIcon(name: string, isOpen: boolean) {
  const standalone = standaloneFolderIcons[name];
  return {
    src: `/vscode-icons/${standalone ?? `${specialFolderTypes[name] ?? "default_folder"}${isOpen ? "_opened" : ""}`}.svg`,
    badge: standalone ? undefined : specialFolderBadges[name],
  };
}
